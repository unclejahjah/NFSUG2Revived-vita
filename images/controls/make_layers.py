"""Writes src/ug2/diagram_art.h (run-length coded body and leader layers) and diagram_layout.h. Texture 1024x512 at
1024/848 texels a unit: x -424..424, y 183 +/- 212."""
import math
import os

import make_diagrams as md
import picture_layout as pl

W, H = 1024, 512
K = W / (pl.CANVAS[2] - pl.CANVAS[0])
X0 = pl.CANVAS[0]
Y0 = (pl.CANVAS[1] + pl.CANVAS[3]) / 2 - H / K / 2
SRC = os.path.join(md.HERE, "..", "..", "src", "ug2")


def rle(data, bpp):
    """Control byte 0..127 copies n+1 pixels, 128..255 skips n-127."""
    out = bytearray()
    n = len(data) // bpp
    i = 0
    while i < n:
        zero = not any(data[i * bpp:(i + 1) * bpp])
        j = i
        while j < n and j - i < 128 and (not any(data[j * bpp:(j + 1) * bpp])) == zero:
            j += 1
        if zero:
            out.append(127 + j - i)
        else:
            out.append(j - i - 1)
            out += data[i * bpp:j * bpp]
        i = j
    return bytes(out)


def crop(img):
    box = img.getchannel("A").getbbox()
    if not box:
        return img.crop((0, 0, 1, 1)), (0, 0)
    return img.crop(box), (box[0], box[1])


def to_la(img):
    from PIL import Image
    r, _, _, a = img.split()
    return Image.merge("LA", (r, a))


def emit(name, data):
    lines = ["const uint8_t %s[%d] =\n{" % (name, len(data))]
    for i in range(0, len(data), 40):
        lines.append("    " + ",".join("%d" % b for b in data[i:i + 40]) + ",")
    lines.append("};\n")
    return "\n".join(lines)


def camel(name):
    return "".join(w.capitalize() for w in name.split("_"))


def layout_header(lines):
    slots = []
    for name in pl.SLOTS:
        side, (x, y), _ = lines[name]
        slots.append('    { "%s", %.2ff, %.2ff, %s },' % (name.upper(), x, y, "true" if side == "R" else "false"))
    return "\n".join([
        "// Generated by images/controls/make_layers.py from picture_layout.py: the Joypad Configuration picture's geometry.",
        "#ifndef UG2_DIAGRAM_LAYOUT_H_", "#define UG2_DIAGRAM_LAYOUT_H_", "",
        "namespace ug2 { namespace diagramlayout {", "",
        "const int Width = %d, Height = %d;    // texels" % (W, H),
        "// Texels a unit, and the texture's top left in Front End units (x from the screen centre).",
        "const float Scale = %.6ff, OriginX = %.2ff, OriginY = %.2ff;" % (K, X0, Y0),
        "const float LabelRoom = %.1ff;     // widest label, units" % (math.floor(pl.LABEL_ROOM * 10) / 10),
        "// The dark box the layout fits in: left, top, right, bottom, x from the screen centre.",
        "const float Box[4] = { %.1ff, %.1ff, %.1ff, %.1ff };" % pl.BOX,
        "// The slots; Slots and diagramart::Layers follow this order.",
        "enum SlotId { %s, SlotCount };" % ", ".join("Slot" + camel(n) for n in pl.SLOTS),
        "const int ControlSlots = Slot%s;" % camel(pl.SLOTS[len(pl.SLOTS) - 4]), "",
        "// A slot's label: name, the column edge and the row centre; right column texts start there, left ones end.",
        "struct Slot { const char* name; float x, y; bool right; };",
        "const Slot Slots[SlotCount] =", "{"] + slots + ["};", "", "}}", "", "#endif /* !UG2_DIAGRAM_LAYOUT_H_ */", ""])


def make_layers(screen_uri, profile, tmp):
    lines = pl.leaders()
    out, table = [], []

    def add(name, label, img, x, y, rgba):
        layer = img if rgba else to_la(img)
        data = rle(layer.tobytes(), 4 if rgba else 2)
        out.append(emit("Data" + label, data))
        table.append('    { "%s", %d, %d, %d, %d, %s, Data%s, %d },' % (name, x, y, layer.width, layer.height,
                                                                         "true" if rgba else "false", label, len(data)))
        return len(data)

    img, (bx, by) = crop(md.render(md.body_svg(screen_uri), W, H, K, X0, Y0, profile, tmp, "body"))
    total = add("BODY", "Body", img, bx, by, True)
    for name in pl.SLOTS:
        img, (lx, ly) = crop(md.render(md.leader_svg(lines[name][2]), W, H, K, X0, Y0, profile, tmp, name))
        total += add(name.upper(), "Leader" + camel(name), img, lx, ly, False)
    head = ["// Generated by images/controls/make_layers.py: the Joypad Configuration picture's layers, run-length coded "
            "(see the script).",
            "#ifndef UG2_DIAGRAM_ART_H_", "#define UG2_DIAGRAM_ART_H_", "", "#include <cstdint>", "",
            '#include "diagram_layout.h"', "", "namespace ug2 { namespace diagramart {", "",
            "// Layer images. name: BODY or the slot's; x, y: where it sits in the texture; rgba: else luminance and alpha.",
            "struct Layer { const char* name; int x, y, w, h; bool rgba; const uint8_t* data; int bytes; };", ""]
    tail = ["// The body, then one leader per slot in diagramlayout::SlotId order.",
            "const Layer Layers[1 + diagramlayout::SlotCount] =", "{"] + table + [
            "};", "", "const int BodyLayer = 0, LeaderLayer = 1;", "", "}}", "", "#endif /* !UG2_DIAGRAM_ART_H_ */", ""]
    with open(os.path.join(SRC, "diagram_art.h"), "w") as f:
        f.write("\n".join(head) + "\n" + "\n".join(out) + "\n" + "\n".join(tail))
    with open(os.path.join(SRC, "diagram_layout.h"), "w") as f:
        f.write(layout_header(lines))
    print("wrote diagram_art.h (%d bytes of layers) and diagram_layout.h: %dx%d texels, %.4f a unit, origin %.1f, %.1f"
          % (total, W, H, K, X0, Y0))
